s32 CArGBAOdh::cdj_c_initializeCompressOdh(SArCDJ_OdhMaster* master, u16* dimensions, u8 requestedQuality, u8* workBuffer, u8* outputBuffer, u32 outputCapacity) {
    u32 dimensionMinusOne;
    u32 quantizationScale;
    s32 result;

    if ((((*dimensions == 0) || (0x7FF < *dimensions)) || (dimensions[1] == 0)) || (0x7FF < dimensions[1])) {
        result = ODH_ERROR_80000001;
    } else if (requestedQuality > 0x64) {
        result = ODH_ERROR_80000002;
    } else {
        master->workBuffer = workBuffer;
        master->data = outputBuffer;
        master->width = *dimensions;
        master->height = dimensions[1];
        master->quality = requestedQuality;
        dimensionMinusOne = *dimensions - 1;
        master->blocksWide = (s32)dimensionMinusOne / 8 + 1;
        dimensionMinusOne = dimensions[1] - 1;
        master->blocksHigh = (s32)dimensionMinusOne / 8 + 1;
        master->luminanceRequest.predictors[0] = &master->field20;
        master->luminanceRequest.predictors[1] = &master->field20;
        master->luminanceRequest.dcTable = (u32*)gArDC_L_Table;
        master->luminanceRequest.acTable = (u32*)gArDC_L_Table;
        master->luminanceRequest.bitstream = outputBuffer;
        master->luminanceRequest.remaining = &master->remaining;
        master->luminanceRequest.bitBuffer = &master->bitBuffer;
        master->luminanceRequest.bitCount = &master->bitCount;
        master->luminanceRequest.bytesConsumed = outputCapacity;
        master->chrominanceRequest.predictors[0] = &master->field24;
        master->chrominanceRequest.predictors[1] = &master->field28;
        master->chrominanceRequest.dcTable = (u32*)gArDC_C_Table;
        master->chrominanceRequest.acTable = (u32*)gArDC_L_Table;
        master->chrominanceRequest.bitstream = outputBuffer;
        master->chrominanceRequest.remaining = &master->remaining;
        master->chrominanceRequest.bitBuffer = &master->bitBuffer;
        master->chrominanceRequest.bitCount = &master->bitCount;
        master->chrominanceRequest.bytesConsumed = outputCapacity;
        u32 quality = requestedQuality;
        if (quality == 0) {
            quality = 1;
        }
        if (quality < 0x32) {
            quantizationScale = 5000U / (u32)quality;
        } else {
            quantizationScale = 200 - (quality << 1);
        }
        cdj_c_setQuantizationTable(master, quantizationScale);
        master->blockX = 0;
        master->blockY = 0;
        master->bitBuffer = 0;
        master->bitCount = 0x20;
        master->outputPos = outputCapacity;
        master->remaining = outputCapacity - 0x10;
        master->field20 = 0;
        master->field24 = 0;
        master->field28 = 0;
        result = 0;
    }

    return result;
}

s32 CArGBAOdh::cdj_c_compressLoop(SArCDJ_OdhMaster* master) {
    int statusOrOffset;
    int workOffset;
    do {
        int rowOffset = (u32)master->blockY << 6;
        int blocksWide = master->blocksWide;
        int columnOffset = (u32)master->blockX << 3;
        workOffset = blocksWide * rowOffset + columnOffset;
        u32 stride = (u32)master->blocksWide << 3;
        fdct_fast(master->coefficients, (u8*)((u32)master->workBuffer + workOffset), stride,
                  master->quantizationTables);
        for (int i = 0; i < 0x40; i++) {
            u8 index = odh_zigzag_order[i];
            master->dcCoefficients[index] = master->coefficients[i] << 0x10;
        }
        master->coefficients[0] = 0x40004000;
        statusOrOffset = huffmanCoder((u16*)master->dcCoefficients - 1, &master->luminanceRequest);
        if (statusOrOffset == ODH_ERROR_80000004) {
            statusOrOffset = ODH_ERROR_80000004;
            goto done;
        }
        int nextBlocksWide = master->blocksWide;
        int blocksHigh = master->blocksHigh;
        int rowStride = nextBlocksWide << 6;
        statusOrOffset = blocksHigh * rowStride;
        workOffset = workOffset + statusOrOffset;
        u32 nextStride = (u32)nextBlocksWide << 3;
        fdct_fast(master->coefficients, (u8*)((u32)master->workBuffer + workOffset), nextStride,
                  master->quantizationTables + 64);
        for (int i = 0; i < 0x40; i++) {
            u8 index = odh_zigzag_order[i];
            master->dcCoefficients[index] = master->coefficients[i] & 0xFFFF;
        }
        workOffset += (u32)master->blocksHigh * ((u32)master->blocksWide << 6);
        fdct_fast(master->coefficients, (u8*)((u32)master->workBuffer + workOffset),
                  (u32)master->blocksWide << 3, master->quantizationTables + 64);
        for (int i = 0; i < 0x40; i++) {
            u8 index = odh_zigzag_order[i];
            master->dcCoefficients[index] =
                master->coefficients[i] << 0x10 | master->dcCoefficients[index];
        }
        master->coefficients[0] = 0x40004000;
        statusOrOffset = huffmanCoder((u16*)master->dcCoefficients, &master->chrominanceRequest);
        if (statusOrOffset == ODH_ERROR_80000004) {
            statusOrOffset = ODH_ERROR_80000004;
            goto done;
        }
        int nextBlockX = master->blockX + 1;
        master->blockX = nextBlockX;
        if ((u16)nextBlockX == master->blocksWide) {
            master->blockX = 0;
            master->blockY = master->blockY + 1;
        }
    } while (master->blockY < master->blocksHigh);
    statusOrOffset = cdj_c_flashBuffer(master);
    if (statusOrOffset == ODH_ERROR_80000004) {
        statusOrOffset = ODH_ERROR_80000004;
    } else {
        cdj_c_makeHeader(master, master->outputPos - master->remaining);
        statusOrOffset = master->outputPos - master->remaining;
    }

done:
    return statusOrOffset;
}

s32 CArGBAOdh::cdj_c_flashBuffer(SArCDJ_OdhMaster* master) {
    master->bitBuffer |= 0x7F << (master->bitCount -= 7);

    while (master->bitCount <= 0x18) {
        if (master->remaining == 0) {
            return ODH_ERROR_80000004;
        }

        master->data[master->outputPos - master->remaining] = master->bitBuffer >> 24;
        master->remaining--;
        master->bitCount += 8;
        master->bitBuffer <<= 8;
    }

    while ((master->outputPos - master->remaining) & 3) {
        master->data[master->outputPos - master->remaining] = 0xFF;
        master->remaining--;
    }

    return ODH_ERROR_SUCCESS;
}

void CArGBAOdh::cdj_c_setQuantizationTable(SArCDJ_OdhMaster* master, u32 qualityScale) {
    int i;
    u32 temp;
    u32 table;
    u8 quantization[128];

    for (table = 0; table < 2; table++) {
        for (i = 0; i < 64; i++) {
            temp = (qualityScale * gArCdj_std_quant_tbl[table * 64 + i] + 50) / 100;
            if (temp == 0) {
                temp = 1;
            }
            if (temp > 255) {
                temp = 255;
            }
            quantization[table * 64 + i] = temp;
        }
    }

    for (table = 0; table < 2; table++) {
        for (i = 0; i < 64; i++) {
            temp = ((const u16*)gArAANScales)[i];
            temp *= quantization[table * 64 + i];
            temp = 0x4000000 / temp;
            master->quantizationTables[table * 64 + i] = temp;
        }
    }
}

void CArGBAOdh::cdj_c_makeHeader(SArCDJ_OdhMaster* master, u32 size) {
    master->data[0] = 'A';
    master->data[1] = 'J';
    master->data[2] = 'P';
    master->data[3] = 'G';
    *(u32*)&master->data[4] = master->width | (u32)master->height << 11 | (u32)master->quality << 24;
    *(u32*)&master->data[8] = size;
    *(u32*)&master->data[12] = 0;
}

s32 CArGBAOdh::cdj_c_colorConv(SArCDJ_OdhMaster* master, u8* sourceData, int format) {
    u32 paddedWidth;
    u16 width;
    u16 height;
    u8* workPlane;
    int sourceStride;
    u8* crPlane;
    u8* cbPlane;
    u16* dimensions;
    int rowIndex;
    int i;
    u16 dimension;
    u16 paddedDimensions[2];

    dimensions = &master->width;
    width = dimensions[0];
    if ((width & 1) != 0 || (dimensions[1] & 1) != 0) {
        return 1;
    }
    height = dimensions[1];

    for (i = 0; i < 2; i++) {
        dimension = dimensions[i];
        if ((dimension & 7) != 0) {
            paddedDimensions[i] = (dimension + 8) - (dimension & 7);
        } else {
            paddedDimensions[i] = dimension;
        }
    }

    workPlane = master->workBuffer;
    cbPlane = workPlane + (u32)paddedDimensions[0] * (u32)paddedDimensions[1];
    crPlane = cbPlane + (u32)paddedDimensions[0] * (u32)paddedDimensions[1];
    if (format == 0) {
        sourceStride = (width & 0xFFFC) << 3;
    } else {
        sourceStride = (width & 0xFFF8) << 2;
        if (format == 1) {
            sourceStride = (width & 0xFFFC) << 4;
        }
    }

    paddedWidth = paddedDimensions[0];
    for (rowIndex = 0; rowIndex < (s32)height; rowIndex++) {
        LineConv11(sourceData + (rowIndex & 3) * 8 + rowIndex / 4 * sourceStride, workPlane, cbPlane, crPlane,
                   dimensions[0], dimensions[1], (const long*)gArConvPlttTbl, format);
        workPlane += paddedWidth;
        cbPlane += paddedWidth;
        crPlane += paddedWidth;
    }

    return 0;
}

void CArGBAOdh::LineConv11(u8* source, u8* lumaOutput, u8* cbOutput, u8* crOutput, u16 width, u16 height,
                           const long* conversionTable, int format) {
    u32 planeSize = (u32)width * (u32)height;
    const s32* table = (const s32*)conversionTable;
    u32 pixelIndex = 0;

    for (int i = 0; i < width; i++) {
            s32 red;
            s32 green;
            s32 blue;

            if (format == 0) {
                u8* pixelSource = source + (pixelIndex & 0x1FFFFFFC) * 8 + (pixelIndex & 3) * 2;
                u16 pixel = pixelSource[1];
                pixel |= (u16)pixelSource[0] << 8;
                red = (pixel >> 11) & 0x1F;
                green = (pixel >> 6) & 0x1F;
                blue = pixel & 0x1F;
            } else if (format == 1) {
                int blueOrPixelOffset = (pixelIndex & 0xFFFFFFFC) * 0x10 + (pixelIndex & 3) * 2;
                u8* pixel = source + blueOrPixelOffset;
                red = pixel[1] >> 3;
                green = pixel[0x20] >> 3;
                blue = pixel[0x21] >> 3;
            } else {
                int sourceOffset = (pixelIndex & 7) + (pixelIndex & 0x3FFFFFF8) * 4;
                float y = (float)source[sourceOffset] - colorConvert16;
                float cb = (float)source[planeSize + sourceOffset] - colorConvert128;
                float cr = (float)source[planeSize * 2 + sourceOffset] - colorConvert128;
                red = (int)(colorConvertY * y + colorConvertR * cr);
                green = (int)(colorConvertY * y - colorConvertG1 * cb - colorConvertG2 * cr);
                blue = (int)(colorConvertY * y + colorConvertB * cb);

                if (red < 0) {
                    red = 0;
                }
                if (0xFF < red) {
                    red = 0xFF;
                }
                if (green < 0) {
                    green = 0;
                }
                if (0xFF < green) {
                    green = 0xFF;
                }
                if (blue < 0) {
                    blue = 0;
                }
                if (0xFF < blue) {
                    blue = 0xFF;
                }

                red >>= 3;
                green >>= 3;
                blue >>= 3;
            }

            int cbValue = (table[red + 0x60] + table[green + 0x80] + table[blue + 0xA0]) >> 16;
            int crValue = (table[red + 0xC0] + table[green + 0xE0] + table[blue + 0x100]) >> 16;
            int luma = (table[red + 0] + table[green + 0x20] + table[blue + 0x40]) >> 16;

            *lumaOutput++ = (u8)luma;
            *cbOutput++ = (u8)cbValue;
            *crOutput++ = (u8)crValue;
            pixelIndex++;
    }
}
void CArGBAOdh::fdct_fast(u32* coefficients, u8* samples, u32 stride, u32* quantizationTable) {
    int tmp0, tmp1, tmp2, tmp3, tmp4, tmp5, tmp6, tmp7;
    int tmp10, tmp11, tmp12, tmp13;
    int z1, z2, z3, z4, z5, z11, z13;
    int* buffer;
    int counter;

    for (counter = 0; counter < 8; counter++) {
        for (int row = 0, outputRow = 0; row < 8; row++, outputRow += 8) {
            ((int*)coefficients)[counter + outputRow] = (int)samples[counter + row * stride] - 0x80;
        }
    }

    buffer = (int*)coefficients;
    for (counter = 0; counter < 8; counter++) {
        tmp0 = buffer[0] + buffer[7];
        tmp7 = buffer[0] - buffer[7];
        tmp1 = buffer[1] + buffer[6];
        tmp6 = buffer[1] - buffer[6];
        tmp2 = buffer[2] + buffer[5];
        tmp5 = buffer[2] - buffer[5];
        tmp3 = buffer[3] + buffer[4];
        tmp4 = buffer[3] - buffer[4];

        tmp10 = tmp0 + tmp3;
        tmp13 = tmp0 - tmp3;
        tmp11 = tmp1 + tmp2;
        tmp12 = tmp1 - tmp2;

        buffer[0] = tmp10 + tmp11;
        buffer[4] = tmp10 - tmp11;

        z1 = (tmp12 + tmp13) * 181 >> 8;
        buffer[2] = tmp13 + z1;
        buffer[6] = tmp13 - z1;

        tmp10 = tmp4 + tmp5;
        tmp11 = tmp5 + tmp6;
        tmp12 = tmp6 + tmp7;

        z5 = (tmp10 - tmp12) * 98 >> 8;
        z2 = (tmp10 * 139 >> 8) + z5;
        z4 = (tmp12 * 334 >> 8) + z5;
        z3 = tmp11 * 181 >> 8;

        z11 = tmp7 + z3;
        z13 = tmp7 - z3;

        buffer[5] = z13 + z2;
        buffer[3] = z13 - z2;
        buffer[1] = z11 + z4;
        buffer[7] = z11 - z4;
        buffer += 8;
    }

    buffer = (int*)coefficients;
    for (counter = 0; counter < 8; counter++) {
        tmp0 = buffer[0] + buffer[56];
        tmp7 = buffer[0] - buffer[56];
        tmp1 = buffer[8] + buffer[48];
        tmp6 = buffer[8] - buffer[48];
        tmp2 = buffer[16] + buffer[40];
        tmp5 = buffer[16] - buffer[40];
        tmp3 = buffer[24] + buffer[32];
        tmp4 = buffer[24] - buffer[32];

        tmp10 = tmp0 + tmp3;
        tmp13 = tmp0 - tmp3;
        tmp11 = tmp1 + tmp2;
        tmp12 = tmp1 - tmp2;

        buffer[0] = tmp10 + tmp11;
        buffer[32] = tmp10 - tmp11;

        z1 = (tmp12 + tmp13) * 181 >> 8;
        buffer[16] = tmp13 + z1;
        buffer[48] = tmp13 - z1;

        tmp10 = tmp4 + tmp5;
        tmp11 = tmp5 + tmp6;
        tmp12 = tmp6 + tmp7;

        z5 = (tmp10 - tmp12) * 98 >> 8;
        z2 = (tmp10 * 139 >> 8) + z5;
        z4 = (tmp12 * 334 >> 8) + z5;
        z3 = tmp11 * 181 >> 8;

        z11 = tmp7 + z3;
        z13 = tmp7 - z3;

        buffer[40] = z13 + z2;
        buffer[24] = z13 - z2;
        buffer[8] = z11 + z4;
        buffer[56] = z11 - z4;
        buffer++;
    }

    for (counter = 0; counter < 8; counter++) {
        for (int row = 0; row < 8; row++) {
            ((s32*)coefficients)[row * 8 + counter] = (((s32*)coefficients)[row * 8 + counter] * ((s32*)quantizationTable)[row * 8 + counter] + 16384) >> 15;
        }
    }
}

s32 CArGBAOdh::huffmanCoder(u16* coefficientInput, SArCDJ_HuffmanRequest* request) {
    u32* predictor;
    u16* blockStart;
    int component;
    s32 value;
    s32 difference;
    s32 magnitude;
    s32 bitCount;
    s32 runLength;
    u32 code;

    this->outputCursor = request->bitstream + (request->bytesConsumed - *request->remaining);
    component = 0;
    blockStart = coefficientInput;
    coefficientInput++;

    while (true) {
        value = *coefficientInput << 16;
        predictor = request->predictors[component];
        value >>= 16;
        coefficientInput += 2;
        difference = value - (s32)*predictor;
        *predictor = value;

        if (difference < 0) {
            magnitude = -difference;
            difference--;
        } else {
            magnitude = difference;
        }
        if (magnitude == 0) {
            bitCount = 0;
        } else {
            bitCount = 1;
            while ((magnitude >>= 1) != 0) {
                bitCount++;
            }
        }
        code = request->dcTable[bitCount];
        magnitude = (difference & ((1 << bitCount) - 1)) | ((code & 0xFFFFFF) << bitCount);
        code = (s32)code >> 24;
        if (EmitBit(magnitude, code + bitCount, request) == ODH_ERROR_80000004) {
            return ODH_ERROR_80000004;
        }

        while (true) {
            runLength = 0;
            while (true) {
                value = *coefficientInput << 16;
                value >>= 16;
                coefficientInput += 2;
                if (value != 0) {
                    break;
                }
                runLength++;
            }
            if (value == 0x4000) {
                break;
            }

            magnitude = runLength;
            if (runLength == 0) {
                bitCount = 0;
            } else {
                bitCount = 1;
                while ((magnitude >>= 1) != 0) {
                    bitCount++;
                }
            }
            code = request->acTable[bitCount];
            magnitude = (runLength & ((1 << bitCount) - 1)) | ((code & 0xFFFFFF) << bitCount);
            code = (s32)code >> 24;
            if (EmitBit(magnitude, code + bitCount, request) == ODH_ERROR_80000004) {
                return ODH_ERROR_80000004;
            }

            if (value < 0) {
                magnitude = -value;
                value--;
            } else {
                magnitude = value;
            }
            if (magnitude == 0) {
                bitCount = 0;
            } else {
                bitCount = 1;
                while ((magnitude >>= 1) != 0) {
                    bitCount++;
                }
            }
            code = request->dcTable[bitCount];
            magnitude = (value & ((1 << bitCount) - 1)) | ((code & 0xFFFFFF) << bitCount);
            code = (s32)code >> 24;
            if (EmitBit(magnitude, code + bitCount, request) == ODH_ERROR_80000004) {
                return ODH_ERROR_80000004;
            }
        }

        if (runLength != 0) {
            code = request->acTable[7];
            if (EmitBit(code & 0xFFFFFF, (s32)code >> 24, request) == ODH_ERROR_80000004) {
                return ODH_ERROR_80000004;
            }
        }

        if (((u32)coefficientInput & 2) == 0) {
            break;
        }
        coefficientInput = blockStart;
        component = 1;
    }

    return 0;
}

s32 CArGBAOdh::EmitBit(long bits, long bitCount, SArCDJ_HuffmanRequest* request) {
    *request->bitBuffer |= (u32)bits << (*request->bitCount - (u32)bitCount);
    *request->bitCount -= (u32)bitCount;

    while (*request->bitCount <= 0x18) {
        if (*request->remaining == 0) {
            return ODH_ERROR_80000004;
        }

        *this->outputCursor = (u8)(*request->bitBuffer >> 0x18);
        this->outputCursor++;
        *request->remaining -= 1;
        *request->bitBuffer <<= 8;
        *request->bitCount += 8;
    }

    return 0;
}

s32 CArGBAOdh::cdj_d_initializeDecompressOdh(SArCDJ_OdhMaster* master, u8* workBuffer, u8* sourceData) {
    u32 packedHeader;
    u32 headerQuality;
    int ySampling;
    int xSampling;
    int widthScale;
    u32 height;
    s32 result;
    u32 width;

    if (!(((sourceData[0] == 'A') && (sourceData[1] == 'J')) &&
          ((sourceData[2] == 'P') && (sourceData[3] == 'G')))) {
        return ODH_ERROR_80000005;
    }

        const u32* headerWords = (const u32*)sourceData;
        packedHeader = headerWords[1];
        width = packedHeader & 0x7FF;
        master->width = (s16)width;
        height = (headerWords[1] >> 0xB) & 0x7FF;
        master->height = (s16)height;
        xSampling = ((headerWords[1] >> 0x16) & 1) + 1;
        master->xSampling = xSampling;
        ySampling = ((headerWords[1] >> 0x17) & 1) + 1;
        master->ySampling = ySampling;
        headerQuality = headerWords[1];
        master->quality = (u8)(headerQuality >> 0x18);

        if (((width == 0) || (0x7FF < width)) ||
            ((height == 0) || (0x7FF < height))) {
            result = ODH_ERROR_80000001;
        } else if ((headerQuality >> 0x18) > 0x64) {
            result = ODH_ERROR_80000002;
        } else {
            master->workBuffer = workBuffer;
            sourceData += 0x10;
            master->data = sourceData;
            widthScale = (xSampling << 3) & 0x7F8;
            master->blocksWide = (int)(width - 1) / widthScale + 1;
            master->blocksHigh = (int)(height - 1) / ((ySampling << 3) & 0x7F8) + 1;
            master->blockX = 0;
            master->blockY = 0;
            master->bitCount = 0;
            master->field20 = 0;
            master->field24 = 0;
            master->field28 = 0;
            master->luminanceRequest.predictors[0] = &master->field20;
            master->luminanceRequest.predictors[1] = &master->field20;
            master->luminanceRequest.bitstream = sourceData;
            master->luminanceRequest.bitCount = &master->bitCount;
            master->luminanceRequest.bytesConsumed = 0x10;
            master->chrominanceRequest.predictors[0] = &master->field24;
            master->chrominanceRequest.predictors[1] = &master->field28;
            master->chrominanceRequest.bitstream = sourceData;
            master->chrominanceRequest.bitCount = &master->bitCount;
            master->chrominanceRequest.bytesConsumed = 0x10;
            u32 quality = headerQuality >> 0x18;
            if (quality == 0) {
                quality = 1;
            }
            u32 scale;
            if (quality < 0x32) {
                scale = 5000U / quality;
            } else {
                scale = 200 - (quality << 1);
            }
            cdj_d_setDequantizationTable(master, scale);
            result = 0;
        }
    return result;
}

